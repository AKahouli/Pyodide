/**
 * Emits the YellowStorm chat widget runtime to the frontend public CDN asset
 * served at {appOrigin}/widget-embed.js.
 *
 * API base resolution (same pattern as the SPA in src/lib/api/config.ts):
 * - VITE_API_URL when explicitly provided (local override only)
 * - otherwise MY_APP_VITE_API_URL — replaced at container start by env.sh
 *
 * Never bake http://localhost:3000 into the committed public asset: that breaks
 * production when the file is deployed as-is.
 *
 * Customer snippets only pass ?token=…
 *
 * Usage (from YellowStorm/front):
 *   npm run emit:widget-embed
 *   VITE_API_URL=https://api.example.com/api/v1 npm run emit:widget-embed
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildWidgetRuntimeSource } from '../src/modules/agent/constants/widget-template.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(__dirname, '../public/widget-embed.js');

function resolveApiBaseUrl() {
  const explicit = process.env.VITE_API_URL?.trim();
  if (explicit) {
    return explicit.replace(/\/$/, '');
  }

  return 'MY_APP_VITE_API_URL';
}

const apiBaseUrl = resolveApiBaseUrl();

const banner = [
  '/* Auto-generated by YellowStorm/front/scripts/emit-widget-embed.mjs — do not edit by hand. */',
  '/* Source of truth: YellowStorm/front/src/modules/agent/constants/widget-template.ts */',
  `/* Baked API base: ${apiBaseUrl} */`,
  '',
].join('\n');

writeFileSync(outPath, banner + buildWidgetRuntimeSource({ apiBaseUrl }) + '\n', 'utf8');
console.log(`Wrote ${outPath} (api=${apiBaseUrl})`);
