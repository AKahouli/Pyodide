async function main(): Promise<void> {
  const files = { ...BASE_FILES };
  const plan = await planPlatformBaseline(
    {
      paths: Object.keys(files),
      read: (p) => Promise.resolve(files[p] ?? null),
    },
    'seed',
  );

  if (plan.violations.length) {
    throw new Error(`Platform baseline refused the starter base: ${plan.violations.join(' ')}`);
  }
  for (const file of plan.files) {
    files[file.path] = file.content;
  }

  fs.rmSync(outDir, { recursive: true, force: true });
  for (const [relative, content] of Object.entries(files)) {
    const out = path.join(outDir, relative);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, content, 'utf8');
  }

  const logoTarget = path.join(outDir, 'public', 'brand', 'yellowsys-logo.svg');
  fs.mkdirSync(path.dirname(logoTarget), { recursive: true });
  fs.copyFileSync(logoSource, logoTarget);

  console.log(
    `Starter v6 materialized at ${outDir} (${Object.keys(files).length + 1} files, ` +
      `${plan.files.length} from the Platform Kit)`,
  );
}

void main();
