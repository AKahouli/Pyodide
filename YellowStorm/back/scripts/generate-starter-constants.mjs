/**
 * Compute embedded starter constants from a local starter directory (no Ceph upload).
 *
 * Usage: node scripts/generate-starter-constants.mjs ../starters/starter-react-vite-v3 starter_react_vite_v3
 */
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const [dirArg, revision] = process.argv.slice(2);
if (!dirArg || !revision) {
  console.error('Usage: node generate-starter-constants.mjs <starter-dir> <revision-id>');
  process.exit(1);
}

const dir = path.resolve(dirArg);
const skip = new Set(['manifest.json', 'README.md', 'package-lock.json', 'node_modules', 'dist']);

function walk(root, relative = '') {
  const out = [];
  for (const entry of fs.readdirSync(path.join(root, relative), { withFileTypes: true })) {
    const rel = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (skip.has(entry.name)) continue;
      out.push(...walk(root, rel));
    } else if (!skip.has(entry.name) && !entry.name.endsWith('.map')) {
      out.push(rel.replace(/\\/g, '/'));
    }
  }
  return out.sort((a, b) => a.localeCompare(b));
}

function blobObjectKey(sha256) {
  return `appbuilder/blobs/sha256/${sha256.slice(0, 2)}/${sha256}`;
}

const files = walk(dir).map((rel) => {
  const body = fs.readFileSync(path.join(dir, rel));
  const sha256 = crypto.createHash('sha256').update(body).digest('hex');
  return { path: rel, sha256, objectKey: blobObjectKey(sha256), size: body.length };
});

const slug = revision.replace(/^starter_/, '').replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();
const manifestKey = `appbuilder/manifests/_system/${revision}.json`;
const outName = revision === 'starter_react_vite_v3' ? 'starter-react-vite-v3.ts' : `${revision}.ts`;
const outFile = path.join(__dirname, '..', 'src', 'modules', 'app-runtime', 'constants', outName);

const fileLines = files
  .map(
    (f) => `  {
    path: '${f.path}',
    sha256: '${f.sha256}',
    objectKey: '${f.objectKey}',
    size: ${f.size},
  }`,
  )
  .join(',\n');

const content = `/**
 * Canonical React/Vite starter revision seeded in Ceph.
 * Manifest: ${manifestKey}
 * Blobs:    appbuilder/blobs/sha256/<aa>/<fullsha>
 *
 * Auto-generated by scripts/generate-starter-constants.mjs — do not edit manually.
 */
export const STARTER_${slug}_REVISION_ID = '${revision}';

export const STARTER_${slug}_MANIFEST_KEY =
  '${manifestKey}';

export interface StarterManifestFile {
  path: string;
  sha256: string;
  objectKey: string;
  size: number;
}

export const STARTER_${slug}_FILES: readonly StarterManifestFile[] = [
${fileLines},
] as const;
`;

fs.writeFileSync(outFile, content);
fs.writeFileSync(
  path.join(dir, 'manifest.json'),
  JSON.stringify({ revisionId: revision, parentRevisionId: null, files }, null, 2),
);
console.log(`Wrote ${outFile} (${files.length} files)`);
